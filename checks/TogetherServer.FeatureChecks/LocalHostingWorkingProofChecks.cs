    internal static async Task PreparedWorkingProofAsync(string root)
    {
        foreach (var fault in new[] { "none", "tamper", "disposed", "cancel", "concurrent", "late-consent", "late-file" })
            await PreparedWorkingProofAsync(root, fault);
        WorkingDirectoryProof(root, substitute: false);
    }

    // Filesystem-native race coverage is separately callable by hosted Windows
    // CI. It opens no app, process, console, browser or desktop surface.
    internal static Task PreparedWorkingNamespaceAsync(string root)
    {
        WorkingDirectoryProof(root, substitute: true);
        return Task.CompletedTask;
    }

    private static void WorkingDirectoryProof(string root, bool substitute)
    {
        using var fixture = new Fixture(root, granted: true);
        var directory = Path.Combine(fixture.Data.RootPath, "working-namespace");
        var nested = Path.Combine(directory, "nested");
        var empty = Path.Combine(directory, "empty");
        var target = Path.Combine(fixture.Data.RootPath, "unrelated-target");
        Directory.CreateDirectory(nested);
        Directory.CreateDirectory(empty);
        Directory.CreateDirectory(target);
        var bytes = Encoding.UTF8.GetBytes("generated nested payload");
        File.WriteAllBytes(Path.Combine(nested, "save.bin"), bytes);
        var marker = Path.Combine(target, "keep.bin");
        File.WriteAllText(marker, "unrelated generated bytes");
        var markerHash = SHA256.HashData(File.ReadAllBytes(marker));
        var version = SharedWorldService.SignVersion(new(4, fixture.GroupId, 1, null, fixture.ProfileId,
            GameKinds.Fixture, "GeneratedNamespace", DateTimeOffset.UtcNow, SharedWorldCaptureKinds.PostStopBackup,
            Guid.NewGuid(), new(fixture.ControlPort, false, "Unknown", [], []),
            [new("nested/save.bin", bytes.Length, Convert.ToHexString(SHA256.HashData(bytes)))], "", "", ""), fixture.PreparedMemberKey);
        var attempted = false;
        var redirected = false;
        Exception? refused = null;
        using (var proof = WorkingSaveStartProof.Open(fixture.Data.RootPath, directory, version, default))
        {
            if (substitute) proof.BeforeDirectoryOpenForChecks = relative =>
            {
                if (relative != "empty") return;
                Require(!attempted, "the generated empty directory was visited twice in one layout pass");
                attempted = true;
                redirected = TryWorkingMountPoint(fixture.Data.RootPath, empty, target);
            };
            try { proof.RequireCurrent(fixture.Data.RootPath, directory, version); }
            catch (Exception error) when (SharedWorldBranchLiveSource.ExpectedFailure(error)) { refused = error; }
        }
        try
        {
            Require(!substitute || attempted, "the namespace proof did not visit its generated empty directory");
            if (substitute && !redirected)
                Console.WriteLine("SKIP native empty-directory substitution: Windows refused the generated reparse mutation; ordinary held-layout checks still ran.");
            Require(redirected ? refused is not null : refused is null,
                "held-handle enumeration either followed an empty-directory substitution or rejected a valid nested/empty layout");
            Require(SHA256.HashData(File.ReadAllBytes(marker)).SequenceEqual(markerHash) &&
                Directory.EnumerateFileSystemEntries(target).SequenceEqual([marker]) &&
                File.ReadAllBytes(Path.Combine(nested, "save.bin")).SequenceEqual(bytes),
                "namespace verification changed the generated payload or unrelated redirect marker");
        }
        finally
        {
            if (redirected)
            {
                Require(AppInstance.ContainsPath(fixture.Data.RootPath, empty) &&
                    (File.GetAttributes(empty) & FileAttributes.ReparsePoint) != 0,
                    "the generated reparse path changed before exact nonrecursive cleanup");
                Directory.Delete(empty, recursive: false);
            }
        }
    }

    private static bool TryWorkingMountPoint(string root, string path, string target)
    {
        Require(AppInstance.ContainsPath(root, path) && AppInstance.ContainsPath(root, target) &&
            Path.IsPathFullyQualified(path) && Path.IsPathFullyQualified(target),
            "the generated native namespace probe escaped disposable storage");
        var substitute = Encoding.Unicode.GetBytes(@"\??\" + target);
        var print = Encoding.Unicode.GetBytes(target);
        var buffer = new byte[16 + substitute.Length + 2 + print.Length + 2];
        BinaryPrimitives.WriteUInt32LittleEndian(buffer, 0xA0000003);
        BinaryPrimitives.WriteUInt16LittleEndian(buffer.AsSpan(4), checked((ushort)(buffer.Length - 8)));
        BinaryPrimitives.WriteUInt16LittleEndian(buffer.AsSpan(10), checked((ushort)substitute.Length));
        BinaryPrimitives.WriteUInt16LittleEndian(buffer.AsSpan(12), checked((ushort)(substitute.Length + 2)));
        BinaryPrimitives.WriteUInt16LittleEndian(buffer.AsSpan(14), checked((ushort)print.Length));
        substitute.CopyTo(buffer, 16);
        print.CopyTo(buffer, 18 + substitute.Length);
        using var handle = OpenWorkingReparseProbe(@"\\?\" + path, 0x100 /* FILE_WRITE_ATTRIBUTES */, 7,
            IntPtr.Zero, 3, 0x02200000, IntPtr.Zero);
        var applied = !handle.IsInvalid && SetWorkingReparseProbe(handle, 0x000900A4, buffer,
            checked((uint)buffer.Length), IntPtr.Zero, 0, out _, IntPtr.Zero);
        if (applied) return true;
        var error = Marshal.GetLastWin32Error();
        if (error is 5 or 32 or 145 or 1314) return false;
        throw new Win32Exception(error, "The generated attribute-only namespace probe failed unexpectedly.");
    }

    [DllImport("kernel32.dll", CharSet = CharSet.Unicode, SetLastError = true, EntryPoint = "CreateFileW")]
    private static extern SafeFileHandle OpenWorkingReparseProbe(string name, uint access, uint share,
        IntPtr security, uint creation, uint flags, IntPtr template);

    [DllImport("kernel32.dll", SetLastError = true, EntryPoint = "DeviceIoControl")]
    [return: MarshalAs(UnmanagedType.Bool)]
    private static extern bool SetWorkingReparseProbe(SafeFileHandle handle, uint operation, byte[] input,
        uint inputLength, IntPtr output, uint outputLength, out uint returned, IntPtr overlapped);

    private static async Task PreparedWorkingProofAsync(string root, string fault)
    {
        using var fixture = new Fixture(root, granted: true, automaticReceiving: true, fileCount: 3, initialVersion: 3);
        var prepared = await fixture.Service.PrepareAsync(fixture.ProfileId, new(true, true));
        Require(prepared is { ReadyForManualStart: true, LocalProfileId: not null, BranchHash: not null },
            "the generated working-proof preparation did not finish");
        var publication = fixture.PublishStoppedContinuation(prepared);
        var workingPath = Path.Combine(publication.Profile.WorldDirectory, "world.dat");
        var sourcePath = Path.Combine(publication.Vault, publication.Version.VersionHash,
            SharedWorldService.PayloadDirectory, "world.dat");
        var extraPath = Path.Combine(publication.Profile.WorldDirectory, "unpublished-late.dat");
        using var peers = fixture.PreparedPublicationPeers();
        await peers.RefreshMembershipsAsync(false, default);
        fixture.PublishPreparedClaim(publication.Branch, publication.Version);
        var latest = await peers.ResolveLatestPreparedStartSourceAsync(fixture.PublicationRoot,
            prepared.LocalProfileId.Value, prepared.BranchHash, default);
        Require(latest is { Ok: true, Source: not null }, "the generated held immutable source was unavailable");
        using var source = latest.Source;
        using var canceled = new CancellationTokenSource();
        var workingHeldBeforeLaunch = false;
        var workingReleasedAtDriver = false;
        var immutableHeldAtDriver = false;
        var verified = 0;
        var driver = new WorkingStartProbeDriver(() =>
        {
            workingReleasedAtDriver = CanWrite(workingPath);
            immutableHeldAtDriver = !CanWrite(sourcePath);
        });
        var manager = new HostManager(fixture.Data, new GameServerRegistry([driver], PortProbeMode.ObserveOnly));
        manager.SharedHostingObservation = peers.LatestObservationHash;
        manager.WorkingSaveVerifiedForChecks = () =>
        {
            verified++;
            Require(!CanWrite(workingPath), "the completed working hash did not retain an immutable lease");
            if (fault == "cancel") canceled.Cancel();
        };
        if (fault == "tamper")
        {
            var before = File.GetLastWriteTimeUtc(workingPath);
            var bytes = File.ReadAllBytes(workingPath);
            bytes[0] ^= 1;
            File.WriteAllBytes(workingPath, bytes);
            File.SetLastWriteTimeUtc(workingPath, before);
        }
        WorkingSaveStartProof? working = null;
        try
        {
            try
            {
                working = await manager.VerifyLocalContinuationForStartAsync(fixture.ProfileId,
                    prepared.LocalProfileId.Value, canceled.Token);
            }
            catch (InvalidDataException) when (fault == "tamper") { }
            catch (OperationCanceledException) when (fault == "cancel" && canceled.IsCancellationRequested) { }
            if (fault is "tamper" or "cancel")
            {
                Require(working is null && driver.StartAttempts == 0 && CanWrite(workingPath),
                    "changed/canceled working verification leaked handles or reached a driver");
                Require(verified == (fault == "cancel" ? 1 : 0), "working verification accepted a same-size, same-time payload change");
                if (fault == "tamper") File.WriteAllBytes(workingPath, File.ReadAllBytes(sourcePath));
                using var recovered = await manager.VerifyLocalContinuationForStartAsync(fixture.ProfileId,
                    prepared.LocalProfileId.Value, default);
                Require(recovered is not null, "failed/canceled verification did not release its exact Start reservation");
                return;
            }
            Require(working is not null && working.VersionHash == publication.Version.VersionHash && verified == 1,
                "the operation did not get one exact full working-save proof");
            Require(!CanWrite(workingPath), "the operation did not hold its verified working bytes");
            if (fault == "concurrent")
            {
                var competing = await Task.WhenAll(Enumerable.Range(0, 2).Select(_ =>
                    manager.VerifyLocalContinuationForStartAsync(fixture.ProfileId, prepared.LocalProfileId.Value, default)));
                Require(competing.All(proof => proof is null) && verified == 1 && !CanWrite(workingPath),
                    "a competing Start opened another working lease or displaced the current operation");
                working.Dispose();
                using var next = await manager.VerifyLocalContinuationForStartAsync(fixture.ProfileId,
                    prepared.LocalProfileId.Value, default);
                Require(next is not null && verified == 2, "disposing the owning proof did not permit a fresh explicit Start");
                return;
            }
            if (fault == "disposed") working.Dispose();
            void RequireScope() => source.RequireCurrent(fixture.Data, fixture.PublicationRoot,
                prepared.LocalProfileId.Value, prepared.BranchHash);
            await manager.RecordHostingObservationAsync(prepared.LocalProfileId.Value, latest,
                RequireScope, default, working);
            manager.BeforeManagedLaunchForChecks = () =>
            {
                workingHeldBeforeLaunch = !CanWrite(workingPath);
                if (fault == "late-consent")
                    Require(new WorldPeerReceiveConsentStore(fixture.Data).Set(fixture.PublicationRoot, fixture.DeviceId, false),
                        "the generated final consent withdrawal failed");
                if (fault == "late-file") File.WriteAllText(extraPath, "not in the signed save");
            };
            var result = await manager.StartSeparateCopyAsync(prepared.LocalProfileId.Value, prepared.BranchHash, default);
            Require(!result.Ok && fixture.Data.LoadRuns().Count == 0, "the fake launch recorded a process or claimed Ready");
            if (fault == "none")
                Require(result.Code == "LaunchFailed" && driver.StartAttempts == 1 && workingHeldBeforeLaunch &&
                    workingReleasedAtDriver && immutableHeldAtDriver && verified == 1,
                    "the common launch boundary did not hold working bytes, release only their lease, and keep the signed source pinned");
            else
                Require(driver.StartAttempts == 0 && !workingReleasedAtDriver && !immutableHeldAtDriver,
                    "disposed proof, late consent or late unpublished content crossed the final process boundary: " + fault);
        }
        finally
        {
            working?.Dispose();
            if (File.Exists(extraPath)) File.Delete(extraPath);
        }
        Require(CanWrite(workingPath), "a rejected or completed Start retained its working-save handles");
    }

    private static bool CanWrite(string path)
    {
        try
        {
            using var stream = new FileStream(path, FileMode.Open, FileAccess.ReadWrite, FileShare.ReadWrite);
            return stream.CanWrite;
        }
        catch (IOException) { return false; }
    }

    // Both methods run in-process. There is no Process.Start or console helper;
    // Start deliberately throws before any operating-system process operation.
    private sealed class WorkingStartProbeDriver(Action onStart) : IGameServerDriver
    {
        internal int StartAttempts { get; private set; }
        public string Kind => GameKinds.Fixture;
        public string DisplayName => "Working proof files-only probe";
        public bool ShowPortDiagnostics => false;
        public bool SupportsCrashRecovery => false;
        public bool SupportsBackups => true;
        public string? ManagedSaveDirectory(ServerProfile profile) => profile.WorldDirectory;
        public string ManagedExecutablePath(ServerProfile profile) => profile.ExecutablePath;
        public IReadOnlyList<GamePort> Ports(ServerProfile profile) => [new("UDP", profile.GamePort, "Game")];
        public string? JoinAddress(ServerProfile profile, string? publicIp) => null;
        public GameValidation? ValidateForStart(ServerProfile profile) => null;
        public void PrepareStart(ServerProfile profile, ManagedRun run) { }
        public GameLaunchResult Start(ServerProfile profile, ManagedRun run)
        {
            StartAttempts++;
            onStart();
            throw new InvalidOperationException("The generated working-proof driver never launches a process.");
        }
        public GameHealthResult Health(ManagedRun run) => throw new InvalidOperationException("No process exists.");
        public Task<GameStopResult> StopAsync(Process process, ManagedRun run) => throw new InvalidOperationException("No process exists.");
    }
}
